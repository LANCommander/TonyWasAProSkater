#!/usr/bin/env python3
"""Replace DAT_xxxxxxxx placeholders in the sources with the demo names in data_names.tsv
(generated by ../tools/data_names.py), and rename the matching key in each source's .syms.json.
The address and the declared type don't change, so the code doesn't either: check with
compile_all.mjs before and after (it compiles .c and .cpp).

  python tools/rename_data.py            report what would change
  python tools/rename_data.py --apply    rewrite src/**/*.{c,cpp,s} and their .syms.json

A name is left as DAT_ in a file where it's already an identifier outside comments and member
accesses: a local, parameter, member or type of that name would capture the reference (and C++
methods see members unqualified). It's
left out everywhere if it's a names.h alias (the macro would turn it into a function symbol) or an
identifier in the Psy-Q SDK headers. Line 1 (when it's the salvage header) and string literals are untouched.
Idempotent: rerun it after data_names.tsv grows.
"""
import collections
import glob
import json
import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from gen_names_h import IDENT, PSYQ_INC, ROOT, STRING, current_aliases, map_body  # noqa: E402

DAT = re.compile(r"\bDAT_([0-9a-f]{8})\b")
COMMENT = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)
MEMBER = re.compile(r"(?:\.|->)\s*[A-Za-z_]\w*")


def main():
    apply = "--apply" in sys.argv
    names = {}
    for l in open(os.path.join(ROOT, "data_names.tsv"), encoding="utf-8"):
        if l.startswith("0x"):
            a, n = l.split("\t")[:2]
            names[int(a, 16)] = n
    banned = set(current_aliases())
    for h in glob.glob(os.path.join(PSYQ_INC, "*.H")) + glob.glob(os.path.join(PSYQ_INC, "*", "*.H")):
        banned.update(IDENT.findall(COMMENT.sub(" ", open(h, encoding="latin1").read())))
    banned &= set(names.values())

    srcs = sorted(f for e in ("c", "cpp", "s") for f in glob.glob(os.path.join(ROOT, "src", "**", f"*.{e}"), recursive=True))
    files = refs = 0
    kept = collections.Counter()     # name -> files where it stayed DAT_ (clash)
    for f in srcs:
        s = open(f, encoding="utf-8", newline="").read()
        header = s.startswith(("/*", "#"))      # the salvage header; otherwise line 1 is code
        body = STRING.sub('""', s.split("\n", 1)[1] if header else s)
        present = {int(a, 16) for a in DAT.findall(body)}
        # identifiers that could capture the name: not in comments, not member accesses (x.f, p->f)
        idents = set(IDENT.findall(MEMBER.sub(" ", COMMENT.sub(" ", body))))
        syms_path = os.path.splitext(f)[0] + ".syms.json"
        syms = json.load(open(syms_path)) if os.path.exists(syms_path) else None
        todo = {}
        for a in present:
            n = names.get(a)
            if not n:
                continue
            if n in banned or n in idents or (syms and n in syms and int(syms[n], 16) != a):
                kept[n] += 1
                continue
            todo[f"DAT_{a:08x}"] = n
        if not todo:
            continue
        files += 1
        sub = lambda t: DAT.sub(lambda m: todo.get(m.group(0), m.group(0)), t)  # noqa: E731
        new = map_body(s, sub) if header else map_body("\n" + s, sub)[1:]
        refs += sum(1 for m in DAT.finditer(body) if m.group(0) in todo)
        if apply:
            open(f, "w", encoding="utf-8", newline="").write(new)
            if syms:
                json.dump({todo.get(k, k): v for k, v in syms.items()}, open(syms_path, "w"), separators=(",", ":"))
    print(f"{'renamed' if apply else 'would rename'} {refs} references in {files} files"
          f"; left as DAT_ (name clash): {sum(kept.values())} file-names, banned names: {len(banned)}")
    for n, c in kept.most_common(25):
        print(f"  {n}: kept in {c} file(s){' (banned)' if n in banned else ''}")


if __name__ == "__main__":
    main()
